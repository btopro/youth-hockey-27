export const GLYPH_W = 5
export const GLYPH_H = 7

export const textWidth = (text, scale) => {
  const s = scale || 1
  return String(text).length * (GLYPH_W + 1) * s - s
}

/**
 * Draw pixel text. align: 'left' | 'center' | 'right'. shadow draws a 1px
 * dark drop shadow for legibility over the ice.
 */
export const drawText = (ctx, text, x, y, color, opts) => {
  const o = opts || {}
  const s = o.scale || 1
  const str = String(text).toUpperCase()
  let sx = x
  const w = textWidth(str, s)
  if (o.align === 'center') sx = Math.round(x - w / 2)
  else if (o.align === 'right') sx = Math.round(x - w)
  const paint = (ox, oy, fill) => {
    ctx.fillStyle = fill
    for (let i = 0; i < str.length; i++) {
      const g = G[str[i]] || G['?']
      for (let row = 0; row < GLYPH_H; row++) {
        const line = g[row]
        for (let col = 0; col < GLYPH_W; col++) {
          if (line[col] === '#') {
            ctx.fillRect(sx + ox + (i * (GLYPH_W + 1) + col) * s, y + oy + row * s, s, s)
          }
        }
      }
    }
  }
  if (o.shadow) paint(s, s, o.shadow)
  paint(0, 0, color)
  return w
}
